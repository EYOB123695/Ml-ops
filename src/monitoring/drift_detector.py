"""
Graph Structure and Embedding Drift Detection Module.

Monitors production data snapshots against a baseline reference graph.
Provides:
  1. Structural Drift: Two-Sample Kolmogorov-Smirnov (KS) test on node degree distributions.
  2. Embedding Drift: Maximum Mean Discrepancy (MMD) with an RBF kernel on
     penultimate-layer node embeddings generated by a FIXED, FROZEN champion model.

IMPORTANT ARCHITECTURAL NOTE:
Why raw embedding coordinates from different model versions are NOT directly comparable:
Neural networks lack coordinate-axis determinism. When a model is retrained—even with
the identical architecture and data using a different random seed or weight initialization—
the resulting latent representations exhibit rotational, reflectional, and permutation symmetries.
Coordinate (0.7, -0.2) in version 1 may represent the exact same semantic feature as
(-0.2, 0.7) in version 2. Therefore, measuring drift across different model weights directly
on raw coordinates is mathematically invalid. We instead monitor embedding drift using a
SINGLE FROZEN ENCODER evaluating incoming data distributions over time.
"""

import numpy as np
from typing import Dict, Tuple
from scipy.stats import ks_2samp
from sklearn.metrics.pairwise import rbf_kernel


class GraphDriftDetector:
    """
    Detects structural and embedding distribution shift between a baseline
    graph snapshot and an incoming production graph snapshot.
    """

    def __init__(
        self,
        baseline_degrees: np.ndarray,
        baseline_embeddings: np.ndarray,
        ks_alpha: float = 0.05,
        mmd_threshold: float = 0.03,
    ):
        """
        Initialize the drift detector with baseline reference statistics.

        Args:
            baseline_degrees: 1D numpy array of node degrees from training/baseline graph.
            baseline_embeddings: 2D numpy array of shape [N, D] representing node
                                 embeddings extracted from the frozen champion model.
            ks_alpha: Significance level for the Kolmogorov-Smirnov test (default: 0.05).
            mmd_threshold: Maximum Mean Discrepancy threshold above which embedding
                           drift is alerted (default: 0.03).
        """
        self.baseline_degrees = np.asarray(baseline_degrees, dtype=np.float64)
        self.baseline_embeddings = np.asarray(baseline_embeddings, dtype=np.float32)
        self.ks_alpha = ks_alpha
        self.mmd_threshold = mmd_threshold

        self.baseline_stats = {
            "num_nodes": len(self.baseline_degrees),
            "mean_degree": float(np.mean(self.baseline_degrees)),
            "median_degree": float(np.median(self.baseline_degrees)),
            "std_degree": float(np.std(self.baseline_degrees)),
        }

    def check_structural_drift(self, current_degrees: np.ndarray) -> Dict:
        """
        Test whether the incoming graph degree distribution diverges significantly
        from the baseline reference using a Two-Sample Kolmogorov-Smirnov test.

        Args:
            current_degrees: 1D numpy array of node degrees from the new graph snapshot.

        Returns:
            Dictionary containing KS statistic, p-value, drift flag, and summary message.
        """
        current_degrees = np.asarray(current_degrees, dtype=np.float64)
        ks_stat, p_val = ks_2samp(self.baseline_degrees, current_degrees)

        drift_detected = bool(p_val < self.ks_alpha)

        return {
            "metric": "degree_distribution_ks_test",
            "ks_statistic": round(float(ks_stat), 6),
            "p_value": round(float(p_val), 6),
            "alpha_threshold": self.ks_alpha,
            "drift_detected": drift_detected,
            "baseline_mean_degree": round(self.baseline_stats["mean_degree"], 2),
            "current_mean_degree": round(float(np.mean(current_degrees)), 2),
            "message": (
                "ALERT: Significant graph structural drift detected (p < alpha). "
                "Degree distribution diverges from baseline."
                if drift_detected
                else "OK: Graph structure is consistent with baseline (no drift)."
            ),
        }

    @staticmethod
    def compute_mmd(X: np.ndarray, Y: np.ndarray, gamma: float = None) -> float:
        """
        Compute the unbiased Maximum Mean Discrepancy (MMD) with an RBF kernel:
            MMD^2(P, Q) = E[k(X, X')] + E[k(Y, Y')] - 2 * E[k(X, Y)]

        Args:
            X: Baseline embeddings [N1, D].
            Y: Current embeddings [N2, D].
            gamma: RBF kernel bandwidth parameter (defaults to 1.0 / D).

        Returns:
            MMD value as a float.
        """
        if gamma is None:
            gamma = 1.0 / max(1, X.shape[1])

        # Subsample if large to maintain real-time performance
        max_samples = 500
        if len(X) > max_samples:
            idx = np.random.choice(len(X), max_samples, replace=False)
            X = X[idx]
        if len(Y) > max_samples:
            idx = np.random.choice(len(Y), max_samples, replace=False)
            Y = Y[idx]

        K_XX = rbf_kernel(X, X, gamma=gamma).mean()
        K_YY = rbf_kernel(Y, Y, gamma=gamma).mean()
        K_XY = rbf_kernel(X, Y, gamma=gamma).mean()

        mmd_sq = K_XX + K_YY - 2.0 * K_XY
        return float(max(0.0, mmd_sq))

    def check_embedding_drift(
        self, current_embeddings: np.ndarray, gamma: float = None
    ) -> Dict:
        """
        Evaluate distribution divergence of node representations using MMD
        computed from the fixed champion model.

        Args:
            current_embeddings: 2D numpy array [N, D] of embeddings from new data.
            gamma: RBF kernel bandwidth (defaults to 1.0 / D).

        Returns:
            Dictionary with MMD score, alert flag, and diagnostic message.
        """
        current_embeddings = np.asarray(current_embeddings, dtype=np.float32)
        mmd_score = self.compute_mmd(self.baseline_embeddings, current_embeddings, gamma=gamma)

        drift_detected = bool(mmd_score > self.mmd_threshold)

        return {
            "metric": "embedding_maximum_mean_discrepancy_rbf",
            "mmd_score": round(mmd_score, 6),
            "threshold": self.mmd_threshold,
            "drift_detected": drift_detected,
            "message": (
                f"ALERT: Significant embedding drift detected! "
                f"MMD ({mmd_score:.4f}) exceeds threshold ({self.mmd_threshold})."
                if drift_detected
                else f"OK: Embedding representations within normal distribution tolerance "
                f"(MMD={mmd_score:.4f} <= {self.mmd_threshold})."
            ),
        }

    def run_full_diagnostic(
        self, current_degrees: np.ndarray, current_embeddings: np.ndarray
    ) -> Dict:
        """
        Execute both structural and embedding drift evaluations in a unified report.
        """
        struct_res = self.check_structural_drift(current_degrees)
        embed_res = self.check_embedding_drift(current_embeddings)

        any_drift = struct_res["drift_detected"] or embed_res["drift_detected"]

        return {
            "overall_status": "DRIFT_DETECTED" if any_drift else "HEALTHY",
            "structural_check": struct_res,
            "embedding_check": embed_res,
        }
